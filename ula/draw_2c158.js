// ---- ZX81 ULA: the cell circuits of Ferranti drawing ULA 2C158/2, issue 4, redrawn ----
//   node ula/draw_2c158.js <out-dir>       writes 2c158-cells.svg (one A1 sheet)
// The 2C210 is built from these cells: the D latch, the D and T flip-flops, and the pin circuits (inputs, data pins,
// address outputs, the RAM and ROM selects, NMI, the clock output, TV/TAPE and the ceramic oscillator).
// Every part was read from the scan and is drawn where the original draws it: coordinates are pixels of the sheet
// scanned at 150 dpi (10000 x 7038), each cell transcribed in the frame of a crop whose origin is given below.
// Source and terms: ula/README.md (Ferranti archive, strictly non-commercial).
const fs = require('fs'), path = require('path');

const SW = 10000, SH = 7038, K = 7.4963;          // sheet size at 150 dpi; overview (1334 px wide) to sheet
const INK = '#14213d', MUTE = '#6b7280', ACC = '#9a3412';
const MONO = "'DejaVu Sans Mono',monospace", CW = 0.602;   // character width / size for the mono face
const out = [];
const f1 = n => (+n).toFixed(1);

// ---- a cell: maps the crop's coordinates to the sheet ----
let ox = 0, oy = 0, sc = 1;
function cell(ovx, ovy, scale = 1) { ox = ovx * K; oy = ovy * K; sc = scale; }
const X = x => ox + x * sc, Y = y => oy + y * sc;
const P = (x, y) => `${f1(X(x))},${f1(Y(y))}`;

// wires: W([x,y], [x,y], ...) ; dashed with W.d
function W(...pts) { out.push(`<polyline points="${pts.map(([x, y]) => P(x, y)).join(' ')}" fill="none"/>`); }
W.d = (...pts) => out.push(`<polyline points="${pts.map(([x, y]) => P(x, y)).join(' ')}" fill="none" stroke-dasharray="22 14"/>`);
const dot = (x, y) => out.push(`<circle cx="${f1(X(x))}" cy="${f1(Y(y))}" r="10" fill="${INK}" stroke="none"/>`);

// text with ~overlined~ parts, in the mono face
function T(x, y, s, size = 44, anchor = 'start', fill = INK, extra = '') {
  const plain = s.replace(/~/g, ''), w = plain.length * CW * size;
  const x0 = anchor === 'middle' ? X(x) - w / 2 : anchor === 'end' ? X(x) - w : X(x);
  out.push(`<text x="${f1(x0)}" y="${f1(Y(y))}" font-size="${size}" fill="${fill}" stroke="none" font-family="${MONO}"${extra}>${plain.replace(/&/g, '&amp;').replace(/</g, '&lt;')}</text>`);
  let i = 0, on = false, start = 0;
  for (const ch of s) {
    if (ch === '~') { if (on) out.push(`<line x1="${f1(x0 + start * CW * size)}" y1="${f1(Y(y) - size * 0.86)}" x2="${f1(x0 + i * CW * size)}" y2="${f1(Y(y) - size * 0.86)}" stroke-width="3"/>`); else start = i; on = !on; continue; }
    i++;
  }
}
function title(x, y, s) {                         // underlined twice, as on the original
  const size = 62, w = s.replace(/~/g, '').length * CW * size;
  T(x, y, s, size);
  out.push(`<line x1="${f1(X(x))}" y1="${f1(Y(y) + 16)}" x2="${f1(X(x) + w)}" y2="${f1(Y(y) + 16)}" stroke-width="4"/>`);
  out.push(`<line x1="${f1(X(x))}" y1="${f1(Y(y) + 28)}" x2="${f1(X(x) + w)}" y2="${f1(Y(y) + 28)}" stroke-width="4"/>`);
}

// resistor: vertical from (x,y1) to (x,y2) with its body between b1 and b2; label to the right (or 'l' left)
function RV(x, y1, y2, b1, b2, lab, side = 'r') {
  W([x, y1], [x, b1]); W([x, b2], [x, y2]);
  out.push(`<rect x="${f1(X(x) - 30)}" y="${f1(Y(b1))}" width="60" height="${f1(Y(b2) - Y(b1))}" fill="#fff"/>`);
  if (lab) T(side === 'r' ? x + 50 : x - 50, (b1 + b2) / 2 + 15, lab, 44, side === 'r' ? 'start' : 'end');
}
function RH(y, x1, x2, b1, b2, lab, side = 'b') {
  W([x1, y], [b1, y]); W([b2, y], [x2, y]);
  out.push(`<rect x="${f1(X(b1))}" y="${f1(Y(y) - 30)}" width="${f1(X(b2) - X(b1))}" height="60" fill="#fff"/>`);
  if (lab) T((b1 + b2) / 2, side === 'b' ? y + 90 : y - 45, lab, 44, 'middle');
}
// NPN transistor: base bar at x=bx, centre y; side +1 puts collector and emitter to the right; c and e are the y
// the collector and emitter leads run to (vertically from the diagonal's end)
function Q(bx, y, side, c, e, opts = {}) {
  const dx = 60 * side, b = X(bx), yy = Y(y);
  out.push(`<line x1="${f1(b)}" y1="${f1(yy - 62)}" x2="${f1(b)}" y2="${f1(yy + 62)}" stroke-width="6"/>`);
  out.push(`<polyline points="${f1(b)},${f1(yy - 28)} ${f1(b + dx)},${f1(yy - 70)}" fill="none"/>`);
  out.push(`<polyline points="${f1(b)},${f1(yy + 28)} ${f1(b + dx)},${f1(yy + 70)}" fill="none"/>`);
  // arrow on the emitter, pointing out
  const ax = b + dx, ay = yy + 70, ux = dx / Math.hypot(dx, 42), uy = 42 / Math.hypot(dx, 42);
  out.push(`<path d="M${f1(ax)},${f1(ay)} L${f1(ax - ux * 30 - uy * 12)},${f1(ay - uy * 30 + ux * 12)} L${f1(ax - ux * 30 + uy * 12)},${f1(ay - uy * 30 - ux * 12)} Z" fill="${INK}" stroke="none"/>`);
  const cx = bx + 60 * side / sc;
  if (c !== undefined) W([cx, y - 70 / sc], [cx, c]);
  if (e !== undefined) W([cx, y + 70 / sc], [cx, e]);
  if (opts.lab) T(bx - 20 * side, y + 70, opts.lab, 40, side > 0 ? 'end' : 'start');
  return cx;
}
function rail(y, x1, x2, lab, at = 'r') {
  W([x1, y], [x2, y]);
  if (lab) T(at === 'r' ? x2 + 20 : x1 - 20, y + 15, lab, 44, at === 'r' ? 'start' : 'end');
}
function flag(x1, x2, y, dir = 'r') {                    // pin pad, pointing right
  const h = 30;
  out.push(`<path d="M${P(x1, y - h)} L${P(x2 - 55, y - h)} L${P(x2, y)} L${P(x2 - 55, y + h)} L${P(x1, y + h)} Z" fill="#fff"/>`);
}
function pad(x1, x2, y) {                                // the hexagonal bidirectional pad
  const h = 30;
  out.push(`<path d="M${P(x1, y)} L${P(x1 + 45, y - h)} L${P(x2 - 45, y - h)} L${P(x2, y)} L${P(x2 - 45, y + h)} L${P(x1 + 45, y + h)} Z" fill="#fff"/>`);
}
function arrowOut(x1, x2, y, lab) {
  W([x1, y], [x2, y]);
  out.push(`<path d="M${P(x2 - 40, y - 14)} L${P(x2, y)} L${P(x2 - 40, y + 14)}" fill="none"/>`);
  if (lab) T(x2 + 25, y + 15, lab);
}
function diodeUp(x, y1, y2) {                            // anode below, cathode above: the bar at y1
  out.push(`<path d="M${P(x - 50, y2)} L${P(x + 50, y2)} L${P(x, y1)} Z" fill="#fff"/>`);
  out.push(`<line x1="${f1(X(x - 50))}" y1="${f1(Y(y1))}" x2="${f1(X(x + 50))}" y2="${f1(Y(y1))}"/>`);
}
function capH(x1, x2, y) {
  out.push(`<line x1="${f1(X(x1))}" y1="${f1(Y(y - 38))}" x2="${f1(X(x1))}" y2="${f1(Y(y + 38))}" stroke-width="6"/>`);
  out.push(`<line x1="${f1(X(x2))}" y1="${f1(Y(y - 38))}" x2="${f1(X(x2))}" y2="${f1(Y(y + 38))}" stroke-width="6"/>`);
}
function tri(x1, x2, y, { bubble = false, en = false, h = 45 } = {}) {   // buffer symbol
  out.push(`<path d="M${P(x1, y - h)} L${P(x2, y)} L${P(x1, y + h)} Z" fill="#fff"/>`);
  if (bubble) out.push(`<circle cx="${f1(X(x2) + 12)}" cy="${f1(Y(y))}" r="12" fill="#fff"/>`);
  if (en) { const ex = (x1 + x2) / 2 + 10; out.push(`<circle cx="${f1(X(ex))}" cy="${f1(Y(y + h * 0.66))}" r="12" fill="#fff"/>`); W([ex, y + h * 0.66 + 12 / sc], [ex, y + h + 50]); }
}
// NOR gate, body from x to x+w, centre y, inputs at the given y; returns the output point (after the bubble)
function NOR(x, y, ins, { w = 170, h = 130 } = {}) {
  const a = X(x), b = X(x + w), t = Y(y) - h * sc / 2, bt = Y(y) + h * sc / 2, back = 22 * sc, m = Y(y);
  out.push(`<path d="M${f1(a)},${f1(t)} Q${f1(a + (b - a) * 0.6)},${f1(t)} ${f1(b)},${f1(m)} Q${f1(a + (b - a) * 0.6)},${f1(bt)} ${f1(a)},${f1(bt)} Q${f1(a + back)},${f1(m)} ${f1(a)},${f1(t)} Z" fill="#fff"/>`);
  out.push(`<circle cx="${f1(b + 12)}" cy="${f1(m)}" r="12" fill="#fff"/>`);
  for (const iy of ins) { const k = (Y(iy) - m) / (h * sc / 2); W([x - 0.001, iy], [x + (back / sc) * (1 - k * k), iy]); }
  return [x + w + 24 / sc, y];
}

