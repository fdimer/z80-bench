// ---- ZX81 ULA: the netlist as timed, gate-for-gate Verilog ----
//   node ula/gen_verilog.js            writes ula/2c210_gates.v from ula/2c210.net
// One Verilog primitive (or one small flip-flop module) per netlist element, with the same delay ula/sim.js uses,
// so the file is the drawing in Verilog: for simulation and for checking a synchronous design against, not for
// synthesis (it relies on gate delays for its pulses, as the chip does).
// fromVerilog() reads such a file back into netlist text; ula/tb.js uses it (ULA=gates.v) to run the testbench on
// what the Verilog file says rather than on the netlist it came from.
const fs = require('fs'), path = require('path');
const { UlaSim } = require('./sim.js');

const san = n => n === 'VCC' ? "1'b1" : n === 'GND' || n === '-' ? "1'b0" : n.replace(/'/g, 'p').replace(/[^A-Za-z0-9_]/g, '_');

function toVerilog(netText, name) {
  const sim = new UlaSim(netText, { init: {} });
  const pinNo = {}; for (const raw of netText.split('\n')) { const m = /^(\S+)\s+pin_\w+\s+(\S+).*?\bPN(\d+)/.exec(raw); if (m) pinNo[m[2]] = m[3]; }
  const ports = [], wires = new Set(), body = [], pull = new Set();
  const dirOf = {};
  for (const e of sim.els) {
    const o = e.outs[0];
    if (e.type === 'pin_in' || e.type === 'osc') dirOf[o] = 'input';
    else if (e.type === 'pin_io') dirOf[o] = 'inout';
    else if (e.type === 'pin_oc' || e.type === 'pin_ts') dirOf[o] = dirOf[o] === 'input' || (sim.fan[o] || []).length ? 'inout' : dirOf[o] || 'output';
    else if (e.type === 'pin_tp' || e.type === 'pin_tpn' || e.type === 'out3') dirOf[o] = 'output';
  }
  for (const raw of netText.split('\n')) { const m = /^(\S+)\s+pin_(in|io)\s+(\S+).*pullup=/.exec(raw); if (m) pull.add(m[3]); }
  for (const e of sim.els) if (e.type === 'pin_oc') pull.add(e.outs[0]);
  delete dirOf.VCC; delete dirOf.GND;      // supply pins (40 and 34): constants here
  for (const [n, d] of Object.entries(dirOf)) ports.push(`  ${d.padEnd(6)} ${n === 'TV/TAPE' ? '[1:0] ' : ''}${san(n)}${pinNo[n] ? `   // pin ${pinNo[n]}` : ''}`);
  const I = (e, i) => (e.inv[i] ? '~' : '') + san(e.ins[i]);
  for (const e of sim.els) {
    const o = e.outs.map(san), t = e.type, id = 'g_' + san(e.id), d = `#(${e.d})`;
    for (const n of e.outs) if (n !== '-' && n !== 'VCC' && n !== 'GND' && !(n in dirOf)) wires.add(san(n));
    const ins = e.ins.map((_, i) => I(e, i));
    if (t === 'pin_in' || t === 'pin_io' || t === 'osc') continue;
    if (t === 'buf_ef' || t === 'pin_tp') body.push(`  buf    ${d} ${id} (${o[0]}, ${ins[0]});`);
    else if (t === 'inv' || t === 'inv_rtl' || t === 'pin_tpn') body.push(`  not    ${d} ${id} (${o[0]}, ${ins[0]});`);
    else if (/^nor/.test(t)) body.push(`  nor    ${d} ${id} (${o[0]}, ${ins.join(', ')});`);
    else if (/^or/.test(t)) body.push(`  or     ${d} ${id} (${o[0]}, ${ins.join(', ')});`);
    else if (t === 'pin_oc') body.push(`  bufif0 ${d} ${id} (${o[0]}, 1'b0, ${ins[0]});`);
    else if (t === 'pin_ts') body.push(`  bufif1 ${d} ${id} (${o[0]}, ${ins[0]}, ${ins[1]});`);
    else if (t === 'dff') body.push(`  ula_dff    ${d} ${id} (.q(${o[0]}), .d(${ins[0]}), .clk(${ins[1]}), .rst(${ins[2]}));`);
    else if (t === 'tff') body.push(`  ula_tff    ${d} ${id} (.q(${e.outs[0] === '-' ? '' : o[0]}), .qn(${e.outs[1] === '-' ? '' : o[1]}), .clk(${ins[0]}), .rst(${ins[1]}));`);
    else if (t === 'dlatch') body.push(`  ula_dlatch ${d} ${id} (.${/^NQ/.test(e.outs[0]) ? 'qn' : 'q'}(${o[0]}), .d(${ins[0]}), .en(${ins[1]}));`);
    else if (t === 'out3') body.push(`  ula_out3   ${d} ${id} (.level(${o[0]}), .sync(${ins[0]}), .black(${ins[1]}));`);
    else throw new Error('no Verilog for ' + t);
  }
  const al = Object.entries(sim.alias).map(([a, b]) => `// ${a} is ${b}`);
  return `// ${name}: the Ferranti ULA of the Sinclair ZX81, gate for gate, with gate delays.
// GENERATED by ula/gen_verilog.js from ula/${name.replace(/_gates$/, '')}.net; do not edit: change the netlist.
// Source and terms: see ula/README.md. The netlist is a transcription of a Ferranti logic diagram from the Ferranti
// archive, which is for non-commercial use only; so is this file. Strictly not for commercial use of any kind.
//
// For simulation only: the chip makes its pulses from gate delays, which synthesis tools throw away. Delays are in
// nanoseconds and are estimates, not Ferranti's figures. Pins keep the netlist's names (A0p = A0', N_ = active low).
// Open-collector pins and pins with an on-chip pull-up have a pullup here. The cross-coupled NOR latches (NMI on/off,
// frame sync) start unknown in a simulator, as they do in the chip, until the first OUT.
// TV_TAPE is the three-level video pin as a number: 0 sync, 1 black, 2 white.
\`timescale 1ns / 100ps

module ula_dff #(parameter D = 10) (output reg q, input d, input clk, input rst);
  initial q = 1'b0;
  always @(posedge clk or posedge rst) if (rst) q <= #D 1'b0; else q <= #D d;
endmodule

module ula_tff #(parameter D = 10) (output reg q, output qn, input clk, input rst);
  initial q = 1'b0;
  assign qn = ~q;
  always @(posedge clk or posedge rst) if (rst) q <= #D 1'b0; else q <= #D ~q;
endmodule

module ula_dlatch #(parameter D = 8) (output reg q, output qn, input d, input en);
  initial q = 1'b0;
  assign qn = ~q;
  always @(en or d) if (en) q <= #D d;
endmodule

module ula_out3 #(parameter D = 8) (output [1:0] level, input sync, input black);
  assign #D level = sync ? 2'd0 : black ? 2'd1 : 2'd2;
endmodule

module ${name} (
${ports.join(',\n').replace(/(   \/\/ pin \d+),\n/g, ',$1\n')}
);
${al.join('\n')}
  wire ${[...wires].join(', ').replace(/(.{90,}?), /g, '$1,\n       ')};
${[...pull].map(n => `  pullup (${san(n)});`).join('\n')}

${body.join('\n')}
endmodule
`;
}

// Read a generated file back into netlist text (names as in the Verilog).
function fromVerilog(v) {
  const out = [], m0 = /module (ula2c\w+) \(([\s\S]*?)\);/.exec(v);
  for (const l of m0[2].split('\n')) { const m = /^\s*(input|inout|output)\s+(?:\[1:0\] )?(\w+)/.exec(l); if (m && m[1] !== 'output') out.push(`p_${m[2]} ${m[1] === 'input' ? 'pin_in' : 'pin_io'} ${m[2]} PN0`); }
  const un = s => s.trim() === "1'b1" ? 'VCC' : s.trim() === "1'b0" ? 'GND' : s.trim();
  for (const l of v.slice(m0.index).split('\n')) {
    let m;
    if ((m = /^\s*(buf|not|nor|or|bufif0|bufif1)\s+#\(([\d.]+)\) (\w+) \((.*)\);/.exec(l))) {
      const a = m[4].split(',').map(un), k = a.length - 1;
      const type = { buf: 'buf_ef', not: 'inv', nor: 'nor' + k, or: 'or' + k, bufif0: 'pin_oc', bufif1: 'pin_ts' }[m[1]];
      const ins = m[1] === 'bufif0' ? [a[2]] : a.slice(1);
      out.push(`${m[3]} ${type} ${a[0]} ${ins.join(' ')} @0A delay=${m[2]}`);
    } else if ((m = /^\s*ula_(dff|tff|dlatch|out3)\s+#\(([\d.]+)\) (\w+) \((.*)\);/.exec(l))) {
      const p = {}; for (const x of m[4].matchAll(/\.(\w+)\(([^)]*)\)/g)) p[x[1]] = un(x[2]) || '-';
      const z = x => x === 'GND' ? '-' : x;
      if (m[1] === 'dff') out.push(`${m[3]} dff ${p.q} ${p.d} ${p.clk} ${z(p.rst)} @0A delay=${m[2]}`);
      if (m[1] === 'tff') out.push(`${m[3]} tff ${p.q} ${p.qn} ${p.clk} ${z(p.rst)} @0A delay=${m[2]}`);
      if (m[1] === 'dlatch') out.push(`${m[3]} dlatch ${p.qn || p.q} ${p.d} ${p.en} @0A delay=${m[2]}`);   // an inverted output keeps its NQ.. name, which sim.js reads as inverted
      if (m[1] === 'out3') out.push(`${m[3]} out3 ${p.level} ${p.sync} ${p.black} @0A delay=${m[2]}`);
    }
  }
  const text = out.join('\n');
  return text;
}

if (require.main === module) {
  const net = fs.readFileSync(path.join(__dirname, '2c210.net'), 'utf8');
  fs.writeFileSync(path.join(__dirname, '2c210_gates.v'), toVerilog(net, 'ula2c210_gates'));
  console.log('wrote ula/2c210_gates.v');
}
module.exports = { toVerilog, fromVerilog, san };
